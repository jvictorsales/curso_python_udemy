# Aspas simples
print('João Victor')
print('João "Victor"')
print(20*'-')

# Aspas duplas
print("João Victor")
print("João 'Victor'")
print(20*"-")

# Escape
print("João \"Victor\"")

# r
print(r"João \"Victor\"")
